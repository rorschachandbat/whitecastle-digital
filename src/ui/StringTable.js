export function text(key, params = {}) {
  if (!(key in StringTable)) {
    throw new Error(`StringTable 缺少键：${key}`);
  }
  return StringTable[key].replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
